using Maple2.PacketLib.Tools;
using Ms2.Net.Packets;
using NUnit.Framework;

namespace Ms2.Net.Tests;

/// <summary>Ugc (0x6D GMS2) modes 0x0b (a profile picture key) and 0x16 (SetMode). The profile key is masked with '*' by
/// the masking pass. Modes 0x12 and 0x15 are kept as UgcOther and are left as an open difference.</summary>
public class UgcRecordedTests {
    // gms2 recording: packet 39, 127 bytes (names masked with '*' by the masking pass; account/character id bytes replaced with 0x11).
    static readonly byte[] Gms2Profile = new byte[] {
        0x0B, 0x00, 0x00, 0x00, 0x00, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x38, 0x00, 0x2A,
        0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A,
        0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A,
        0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A,
        0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A,
        0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A,
        0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A,
        0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00, 0x2A, 0x00,
    };
    // gms2 recording: packet 25, 5 bytes (names masked with '*' by the masking pass).
    static readonly byte[] Gms2Mode = new byte[] {
        0x16, 0x00, 0x00, 0x00, 0x00,
    };

    [Test] public void Gms2ProfileImageReadsTheCharacterAndKey() {
        var r = new ByteReader(Gms2Profile);
        var u = UgcMessage.Read(r) as UgcProfileImage;
        Assert.That(u, Is.Not.Null);
        Assert.That((u.ObjectId, u.CharacterId), Is.EqualTo((0, 0x1111111111111111L)), "the recorded character id is masked");
        Assert.That(u.Key, Has.Length.EqualTo(56));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2SetModeReadsTheValue() {
        var r = new ByteReader(Gms2Mode);
        var u = UgcMessage.Read(r) as UgcSetMode;
        Assert.That(u, Is.Not.Null);
        Assert.That(u.Value, Is.EqualTo(0));
        Assert.That(r.Available, Is.EqualTo(0));
    }
}
