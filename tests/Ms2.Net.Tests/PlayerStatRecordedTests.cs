    [Test] public void Gms2ThirtyFiveAttributeForm() {
        var r = new ByteReader(Gms2Full);
        var s = PlayerStat.Read(r);
        Assert.That(s.ObjectId, Is.EqualTo(442495));
        Assert.That(s.Values, Has.Count.EqualTo(PlayerStat.Total));
        Assert.That(s.Values[PlayerStat.Health], Is.EqualTo(new long[] { 1037, 1014, 1037 }));
        Assert.That(s.Values[PlayerStat.Spirit], Is.EqualTo(new long[] { 100, 100, 100 }));
        Assert.That(s.Values[PlayerStat.Stamina], Is.EqualTo(new long[] { 120, 120, 120 }));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2ShortFormIsReadByCount() {
        var r = new ByteReader(Gms2Two);
        var s = PlayerStat.Read(r);
        Assert.That((s.ObjectId, s.Values.Count), Is.EqualTo((461271, 2)));
        Assert.That(s.Values[PlayerStat.Health], Is.EqualTo(new long[] { 1328, 1328, 1328 }));
        Assert.That(s.Values[PlayerStat.Spirit], Is.EqualTo(new long[] { 100, 100, 100 }));
        Assert.That(r.Available, Is.EqualTo(0));
    }
