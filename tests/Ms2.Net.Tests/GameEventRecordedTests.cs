    static GameEventMessage DecodeAll(byte[] payload)
    {
        var r = new ByteReader(payload);
        var m = GameEventMessage.Read(r);
        Assert.That(m.Truncated, Is.False);
        Assert.That(r.Available, Is.EqualTo(0));
        return m;
    }

    [Test]
    public void KmsGameEventListPopulatesSpecialAbilityHotTimesAndParsesKind1()
    {
        var m0 = DecodeAll(KmsKind0List);
        Assert.That(m0.Kind, Is.EqualTo((byte)0));
        Assert.That(m0.HotTimes, Is.EqualTo(new[]
        {
            new SpecialAbilityHotTimeEvent(10_319, false, "75,76", "1,1"),
            new SpecialAbilityHotTimeEvent(10_316, false, "71", "1"),
        }));

        var hotTimes = new SpecialAbilityHotTimes(_ => false);
        hotTimes.Apply(m0);
        Assert.That(hotTimes.Count, Is.EqualTo(2));
        Assert.That(hotTimes.Total(75, all: false), Is.EqualTo(1));
        Assert.That(hotTimes.Total(76, all: false), Is.EqualTo(1));
        Assert.That(hotTimes.Total(71, all: false), Is.EqualTo(1));

        var m1 = DecodeAll(KmsKind1Add);
        Assert.That(m1.Kind, Is.EqualTo((byte)1));
        Assert.That(m1.HotTimes, Is.Empty);
    }

    [Test]
    public void Gms2GameEventListPopulatesSpecialAbilityHotTimesAndParsesKind1And2()
    {
        var m0 = DecodeAll(Gms2Kind0List);
        Assert.That(m0.Kind, Is.EqualTo((byte)0));
        Assert.That(m0.HotTimes, Is.EqualTo(new[]
        {
            new SpecialAbilityHotTimeEvent(10_006, false, "1", "9"),
        }));

        var hotTimes = new SpecialAbilityHotTimes(id => id == 1);
        hotTimes.Apply(m0);
        Assert.That(hotTimes.Count, Is.EqualTo(1));
        Assert.That(hotTimes.Total(1, all: false), Is.EqualTo(9_000));

        var m1 = DecodeAll(Gms2Kind1Add);
        Assert.That(m1.Kind, Is.EqualTo((byte)1));
        Assert.That(m1.HotTimes, Is.Empty);

        var m2 = DecodeAll(Gms2Kind2Remove);
        Assert.That(m2.Kind, Is.EqualTo((byte)2));
        Assert.That(m2.RemovedIds, Is.EqualTo(new[] { 440_004 }));
        hotTimes.Apply(m2);
        Assert.That(hotTimes.Count, Is.EqualTo(1));
    }
