using Maple2.PacketLib.Tools;
using Ms2.Net.Packets;
using NUnit.Framework;

namespace Ms2.Net.Tests;

/// <summary>UserEnv (0xAA GMS2) mode 2 (the title list) and mode 5 (no client handler: the count, 0 in the recording, and no
/// body). The reader consumes both exactly.</summary>
public class UserEnvRecordedTests {
    // gms2 recording: packet 2208, 133 bytes (names masked with '*' by the masking pass).
    static readonly byte[] Gms2Titles = new byte[] {
        0x02, 0x20, 0x00, 0x00, 0x00, 0xB5, 0x98, 0x98, 0x00, 0x6F, 0x98, 0x98, 0x00, 0x72, 0x98, 0x98,
        0x00, 0x73, 0x98, 0x98, 0x00, 0x74, 0x98, 0x98, 0x00, 0x60, 0x98, 0x98, 0x00, 0x1A, 0x99, 0x98,
        0x00, 0x13, 0x99, 0x98, 0x00, 0x0C, 0x97, 0x98, 0x00, 0x0D, 0x97, 0x98, 0x00, 0x7B, 0x97, 0x98,
        0x00, 0xA3, 0x97, 0x98, 0x00, 0xA4, 0x97, 0x98, 0x00, 0xA5, 0x97, 0x98, 0x00, 0xA7, 0x97, 0x98,
        0x00, 0xA6, 0x97, 0x98, 0x00, 0xC9, 0x97, 0x98, 0x00, 0xD3, 0x98, 0x98, 0x00, 0xFD, 0x98, 0x98,
        0x00, 0x5D, 0x99, 0x98, 0x00, 0x5E, 0x99, 0x98, 0x00, 0x5F, 0x99, 0x98, 0x00, 0x65, 0x99, 0x98,
        0x00, 0x66, 0x99, 0x98, 0x00, 0x7B, 0x99, 0x98, 0x00, 0x94, 0x99, 0x98, 0x00, 0x95, 0x99, 0x98,
        0x00, 0x96, 0x99, 0x98, 0x00, 0xC2, 0x99, 0x98, 0x00, 0xC3, 0x99, 0x98, 0x00, 0x6A, 0x98, 0x98,
        0x00, 0x6C, 0x98, 0x98, 0x00,
    };
    // gms2 recording: packet 2210, 5 bytes (names masked with '*' by the masking pass).
    static readonly byte[] Gms2Mode5 = new byte[] {
        0x05, 0x00, 0x00, 0x00, 0x00,
    };

    [Test] public void Gms2TitleListReadsThirtyTwoIds() {
        var r = new ByteReader(Gms2Titles);
        var m = UserEnvMessage.Read(r) as UserEnvMessage.Titles;
        Assert.That(m, Is.Not.Null);
        Assert.That(m.Ids, Has.Count.EqualTo(32));
        Assert.That(m.Ids[0], Is.EqualTo(10000565u));
        Assert.That(m.Ids[^1], Is.EqualTo(10000492u));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2Mode5ReadsTheEmptyCount() {
        var r = new ByteReader(Gms2Mode5);
        Assert.That(UserEnvMessage.Read(r), Is.Null);
        Assert.That(r.Available, Is.EqualTo(0));
    }
}
