        0x00, 0x00, 0x00, 0x00, 0x00,
    };

    [Test] public void Gms2ListReadsTwentyEntries() {
        var r = new ByteReader(Gms2);
        var m = EmoteMessage.Read(r, ProtocolProfile.Gms2) as EmoteMessage.List;
        Assert.That(m, Is.Not.Null);
        Assert.That(m.Entries, Has.Count.EqualTo(20));
        Assert.That(m.Entries[0], Is.EqualTo(new EmoteEntry(90200011, 1, false, 0, 0, false)));
        Assert.That(m.Entries[1], Is.EqualTo(new EmoteEntry(90200004, 1, false, 0, 0, false)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void KmsEmptyListIsConsumed() {
        var r = new ByteReader(Kms);
        var m = EmoteMessage.Read(r) as EmoteMessage.List;
        Assert.That(m, Is.Not.Null);
        Assert.That(m.Entries, Is.Empty);
        Assert.That(r.Available, Is.EqualTo(0));
    }
