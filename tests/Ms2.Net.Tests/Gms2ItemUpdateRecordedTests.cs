    static EquipItem Added() {
        var r = new ByteReader(AddFrame);
        var add = (ItemMessage.Add) ItemMessage.Read(r, _ => null, Gms);
        Assert.That(r.Available, Is.EqualTo(0), "the Add reads to its end");
        return add.Item;
    }

    [Test]
    public void TheAddAndTheRemoveReadToTheirEnd() {
        var item = Added();
        Assert.That((item.Id, item.Uid), Is.EqualTo((11300001, Uid)));
        Assert.That(item.Transfer.HasBinding, Is.False, "not bound before the equip");
        var r = new ByteReader(RemoveFrame);
        Assert.That(ItemMessage.Read(r, _ => null, Gms), Is.EqualTo(new ItemMessage.Remove(Uid)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test]
    public void AfterTheRemoveTheUpdateIsSkippedAsTheClientSkipsIt() {
        // the bag no longer has the uid: Update with no item, the body left unread
        var r = new ByteReader(UpdateFrame);
        Assert.That(ItemMessage.Read(r, _ => null, Gms), Is.EqualTo(new ItemMessage.Update(Uid, null)));
        Assert.That(r.Available, Is.EqualTo(UpdateFrame.Length - 9));
    }

    [Test]
    public void TheSkippedBodyIsTheGms2ItemBodyWithTheBindAndZeroBytesLeft() {
        var item = Added();
        var r = new ByteReader(UpdateFrame);
        var m = (ItemMessage.Update) ItemMessage.Read(r, u => u == Uid ? item : null, Gms);
        Assert.That(r.Available, Is.EqualTo(0), "the GMS2 body reads to the end");
        Assert.That(m.Item.Id, Is.EqualTo(11300001));
        Assert.That((m.Item.Transfer.HasBinding, m.Item.Transfer.BindingId, m.Item.Transfer.BindingName),
            Is.EqualTo((true, 7000000002L, "*********")), "bound to the character");
    }
