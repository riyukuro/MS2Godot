    [Test] public void Gms2NormalNpcReadsItsStatsAndBuff() {
        var r = new ByteReader(Gms2);
        var n = FieldAddNpc.Read(r, _ => new NpcLayout(false, false));
        Assert.That((n.ObjectId, n.NpcId), Is.EqualTo((13128, 99000039)));
        Assert.That((n.Position.X, n.Position.Y, n.Position.Z), Is.EqualTo((2555f, -2745f, 3299f)));
        Assert.That(n.Rotation.Z, Is.EqualTo(-72.349884f).Within(0.01f));
        Assert.That(n.BossModelName, Is.Null);
        Assert.That(n.Stats, Has.Length.EqualTo(3));
        Assert.That(n.Stats[0], Is.EqualTo((38788L, 100)));
        Assert.That(n.Buffs, Has.Count.EqualTo(1));
        Assert.That((n.Level, n.Flag), Is.EqualTo((17, false)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2BossNpcReadsItsModelAndSkills() {
        var r = new ByteReader(Gms2Boss);
        var n = FieldAddNpc.Read(r, _ => new NpcLayout(true, false));
        Assert.That((n.ObjectId, n.NpcId), Is.EqualTo((3616168, 22000042)));
        Assert.That(n.BossModelName, Is.EqualTo("22000042_N_RobotHyperRaceWhite"));
        Assert.That(n.Stats[0], Is.EqualTo((746463L, 100)));
        Assert.That((n.Level, n.BossEffect), Is.EqualTo((44, "")));
        Assert.That(n.BossSkills, Has.Length.EqualTo(7));
        Assert.That(n.BossSkills[0], Is.EqualTo((60028011, (short) 1)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void KmsNpcReadsItsStats() {
        var r = new ByteReader(Kms);
        var n = FieldAddNpc.Read(r, _ => new NpcLayout(false, false));
        Assert.That((n.ObjectId, n.NpcId), Is.EqualTo((27337, 11000020)));
        Assert.That((n.Position.X, n.Position.Y, n.Position.Z), Is.EqualTo((2100f, 0f, 1499f)));
        Assert.That(n.Rotation.Z, Is.EqualTo(270f));
        Assert.That(n.Stats[1], Is.EqualTo((29L, 0)));
        Assert.That(n.Buffs, Is.Empty);
        Assert.That(n.Level, Is.EqualTo(10));
        Assert.That(r.Available, Is.EqualTo(0));
    }
