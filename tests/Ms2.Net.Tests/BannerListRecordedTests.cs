    [Test]
    public void KmsBannerListReadsEveryAdBannerRecordToEnd()
    {
        var r = new ByteReader(KmsBannerList);
        var list = BannerList.Read(r);
        Assert.That(r.Available, Is.EqualTo(0));
        Assert.That(list.Banners, Has.Count.EqualTo(7));

        var first = list.Banners[0];
        Assert.That(first.Type, Is.EqualTo(1));
        Assert.That(first.TypeName, Is.EqualTo("left"));
        Assert.That(first.Name, Is.EqualTo("cash"));
        Assert.That(first.Str30, Is.EqualTo(""));
        Assert.That(first.Str38, Is.EqualTo(""));
        Assert.That(first.Str40, Is.EqualTo("*******************************"));
        Assert.That(first.Slot, Is.EqualTo(-1));
        Assert.That(first.Begin, Is.EqualTo(1655708400L));
        Assert.That(first.End, Is.EqualTo(4117158000L));

        var last = list.Banners[6];
        Assert.That(last.Type, Is.EqualTo(9));
        Assert.That(last.TypeName, Is.EqualTo("homeproduct_package_02"));
        Assert.That(last.Name, Is.EqualTo("merat"));
        Assert.That(last.Slot, Is.EqualTo(-1));
        Assert.That(last.Begin, Is.EqualTo(1655708400L));
        Assert.That(last.End, Is.EqualTo(4102473600L));
    }

    [Test]
    public void Gms2BannerListReadsEveryAdBannerRecordToEnd()
    {
        var r = new ByteReader(Gms2BannerList);
        var list = BannerList.Read(r);
        Assert.That(r.Available, Is.EqualTo(0));
        Assert.That(list.Banners, Has.Count.EqualTo(13));

        var first = list.Banners[0];
        Assert.That(first.Type, Is.EqualTo(82));
        Assert.That(first.TypeName, Is.EqualTo("limited_01"));
        Assert.That(first.Name, Is.EqualTo("merat"));
        Assert.That(first.Str30, Is.EqualTo(""));
        Assert.That(first.Str38, Is.EqualTo(""));
        Assert.That(first.Str40.Length, Is.EqualTo(102));
        Assert.That(first.Slot, Is.EqualTo(2));
        Assert.That(first.Begin, Is.EqualTo(1542502800L));
        Assert.That(first.End, Is.EqualTo(1858122000L));

        var last = list.Banners[12];
        Assert.That(last.Type, Is.EqualTo(824));
        Assert.That(last.TypeName, Is.EqualTo("homeproduct_p_special_06"));
        Assert.That(last.Name, Is.EqualTo("merat"));
        Assert.That(last.Slot, Is.EqualTo(-1));
        Assert.That(last.Begin, Is.EqualTo(1584545400L));
        Assert.That(last.End, Is.EqualTo(1590883200L));
    }
