    [Test] public void Gms2AddReadsTheObjectAndItsPosition() {
        var r = new ByteReader(Gms2Add);
        var m = InteractObjectMessage.Read(r);
        Assert.That(m.Mode, Is.EqualTo(InteractObjectMessage.ModeAdd));
        Assert.That((m.Name, m.State, m.Kind, m.RowId), Is.EqualTo(("EventCreate_1506075", (byte) 1, InteractObjectMessage.KindMesh, 14000282)));
        Assert.That((m.Position.X, m.Position.Y, m.Position.Z), Is.EqualTo((4050f, -750f, 3300f)));
        Assert.That((m.Model.Length, m.Scale, m.Flag), Is.EqualTo((16, 1f, false)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2StateReadsTheNameAndKind() {
        var r = new ByteReader(Gms2State);
        var m = InteractObjectMessage.Read(r);
        Assert.That((m.Mode, m.Name, m.State, m.Kind), Is.EqualTo((InteractObjectMessage.ModeState, "EventCreate_1506075", (byte) 2, InteractObjectMessage.KindMesh)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2ResultReadsTheResultAndKind() {
        var r = new ByteReader(Gms2Result);
        var m = InteractObjectMessage.Read(r);
        Assert.That((m.Mode, m.Result, m.Kind), Is.EqualTo((InteractObjectMessage.ModeResult, (byte) 0, InteractObjectMessage.KindMesh)));
        Assert.That((m.Name.Length, r.Available), Is.EqualTo((32, 0)));
    }

    [Test] public void KmsAddReadsTheObject() {
        var r = new ByteReader(KmsAdd);
        var m = InteractObjectMessage.Read(r);
        Assert.That((m.Mode, m.Name, m.State, m.Kind, m.RowId), Is.EqualTo((InteractObjectMessage.ModeAdd, "EventCreate_1311756", (byte) 1, InteractObjectMessage.KindMesh, 14001101)));
        Assert.That(r.Available, Is.EqualTo(0));
    }
