    [Test] public void Gms2EnterReadsTheOwnCharacterAndItsStrings() {
        var r = new ByteReader(Gms2);
        var s = ServerEnter.Read(r, ProtocolProfile.Gms2);
        Assert.That((s.ObjectId, s.CharacterId, s.Channel), Is.EqualTo((1280926, 0x1111111111111111L, 0)), "the recorded character id is masked");
        Assert.That(s.Wallet, Has.Length.EqualTo(14));
        Assert.That(s.UnlockedMaps, Is.Empty);
        Assert.That(s.UnlockedTaxis, Is.Empty);
        Assert.That((s.ChampionGuildId, s.Gms2Flag), Is.EqualTo((0, (byte) 0)));
        Assert.That(s.Gms2Strings, Has.Length.EqualTo(5));
        Assert.That((s.Gms2Strings[0], s.Gms2Strings[2], s.Gms2Strings[4]), Is.EqualTo(("", "", "")));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void KmsEnterReadsTheWalletWithoutGms2Strings() {
        var r = new ByteReader(Kms);
        var s = ServerEnter.Read(r);
        Assert.That((s.ObjectId, s.CharacterId, s.Channel), Is.EqualTo((6121051, 0x1111111111111111L, 0)), "the recorded character id is masked");
        Assert.That(s.Wallet, Has.Length.EqualTo(14));
        Assert.That(s.UnlockedMaps, Is.Empty);
        Assert.That(s.UnlockedTaxis, Is.Empty);
        Assert.That(s.Gms2Strings, Is.Null);
        Assert.That(r.Available, Is.EqualTo(0));
    }
