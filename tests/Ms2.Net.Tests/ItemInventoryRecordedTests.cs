    [Test] public void Gms2AddReadsTheItemBody() {
        var r = new ByteReader(Gms2);
        var a = ItemMessage.Read(r, _ => null, ProtocolProfile.Gms2) as ItemMessage.Add;
        Assert.That(a, Is.Not.Null);
        Assert.That((a.Item.Id, a.Item.Uid, a.Item.Rarity, a.Item.Amount), Is.EqualTo((40100039, 3191390594290960882L, 1, 1)));
        Assert.That(a.Item.CreationTime, Is.EqualTo(1587856268L));
        Assert.That(a.Item.InventorySlot, Is.EqualTo(2));
        Assert.That(r.Available, Is.EqualTo(0));
    }
