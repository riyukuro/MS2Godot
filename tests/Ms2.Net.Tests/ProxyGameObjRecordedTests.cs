/// <summary>ProxyGameObj (0x80 GMS2, 0x7E KMS2): command 3 adds a player (name, picture, motto, position, level, job, home,
/// gear score), 5 updates by flag, 6 adds a template object, 9 a spawn-point object. The names and picture keys are masked
/// with '*' by the masking pass, so only their lengths are asserted.</summary>
public class ProxyGameObjRecordedTests {
    // gms2 recording: packet 2282, 226 bytes (names masked with '*' by the masking pass; account/character id bytes replaced with 0x11; account/character id bytes replaced with 0x11).
    static readonly byte[] Gms2Player = new byte[] {
        0x03, 0x7F, 0xC0, 0x06, 0x00, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
