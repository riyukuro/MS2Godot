    // gms2 recording: packet 2390, 20 bytes (names masked with '*' by the masking pass).
    static readonly byte[] Gms2Update = new byte[] {
        0x05, 0x7F, 0xC0, 0x06, 0x00, 0x42, 0x00, 0x00, 0x16, 0x43, 0x00, 0x80, 0xBB, 0xC4, 0x00, 0x40,
        0x61, 0x44, 0x01, 0x00,
    };
    // gms2 recording: packet 2280, 26 bytes (names masked with '*' by the masking pass).
    static readonly byte[] Gms2Template = new byte[] {
        0x06, 0x8E, 0xC0, 0x06, 0x00, 0x43, 0xDF, 0xA7, 0x00, 0x00, 0xFA, 0x01, 0x00, 0x00, 0x00, 0x00,
        0x96, 0xC3, 0x00, 0x80, 0x3B, 0xC4, 0x00, 0x20, 0x83, 0x44,
    };
    // kms2 recording: packet 1053, 18 bytes (names masked with '*' by the masking pass).
    static readonly byte[] KmsUpdate = new byte[] {
        0x05, 0x27, 0x86, 0xCA, 0x00, 0x02, 0x00, 0xF0, 0x02, 0xC5, 0x00, 0xE0, 0xF6, 0xC4, 0x00, 0xA0,
        0xBB, 0x44,
    };

    [Test] public void Gms2PlayerAddReadsEveryBlock() {
        var r = new ByteReader(Gms2Player);
        var p = ProxyGameObj.Read(r);
        Assert.That((p.Command, p.ObjectId), Is.EqualTo(((byte) 3, 442495)));
        Assert.That((p.CharacterId, p.AccountId), Is.EqualTo((0x1111111111111111L, 0x1111111111111111L)), "the recorded ids are masked");
        Assert.That(p.Name, Has.Length.EqualTo(11));
        Assert.That(p.Picture, Has.Length.EqualTo(56));
        Assert.That(p.Motto, Is.Empty);
        Assert.That((p.Position.X, p.Position.Y, p.Position.Z), Is.EqualTo((150f, -1500f, 900f)));
        Assert.That((p.Level, p.JobCode, p.Job), Is.EqualTo(((short) 22, (short) 90, 900)));
        Assert.That((p.HomePlotMapId, p.HomePlotNumber, p.HomeApartmentNumber), Is.EqualTo((2010002, 5, 0)));
        Assert.That(p.HomeName, Has.Length.EqualTo(6));
        Assert.That((p.GearScore, p.State), Is.EqualTo((353, (short) 0)));
        Assert.That((p.AchievementCombat, p.AchievementAdventure, p.AchievementLifestyle), Is.EqualTo((326, 36, 55)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2UpdateReadsTheFlaggedPositionAndState() {
        var r = new ByteReader(Gms2Update);
        var p = ProxyGameObj.Read(r);
        Assert.That((p.Command, p.ObjectId, p.UpdateFlags), Is.EqualTo(((byte) 5, 442495, 66)));
        Assert.That(p.UpdatePosition, Is.Not.Null);
        Assert.That((p.UpdatePosition.Value.X, p.UpdatePosition.Value.Y, p.UpdatePosition.Value.Z), Is.EqualTo((150f, -1500f, 901f)));
        Assert.That(p.UpdateState, Is.EqualTo((short) 1));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void Gms2TemplateObjectReadsItsIds() {
        var r = new ByteReader(Gms2Template);
        var p = ProxyGameObj.Read(r);
        Assert.That((p.Command, p.ObjectId, p.TemplateId, p.Kind, p.Extra), Is.EqualTo(((byte) 6, 442510, 11001667, (byte) 0, 506)));
        Assert.That((p.Position.X, p.Position.Y, p.Position.Z), Is.EqualTo((-300f, -750f, 1049f)));
        Assert.That(r.Available, Is.EqualTo(0));
    }

    [Test] public void KmsUpdateReadsTheFlaggedPosition() {
        var r = new ByteReader(KmsUpdate);
        var p = ProxyGameObj.Read(r);
        Assert.That((p.Command, p.ObjectId, p.UpdateFlags), Is.EqualTo(((byte) 5, 13272615, 2)));
        Assert.That(p.UpdatePosition, Is.Not.Null);
        Assert.That((p.UpdatePosition.Value.X, p.UpdatePosition.Value.Y, p.UpdatePosition.Value.Z), Is.EqualTo((-2095f, -1975f, 1501f)));
        Assert.That(r.Available, Is.EqualTo(0));
    }
}
